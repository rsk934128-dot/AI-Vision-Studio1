/**
 * Check if running inside Android APK (Capacitor or WebView)
 */
export const isAndroidNativeApp = (): boolean => {
  if (typeof window === 'undefined') return false;
  const isCap = (window as any).Capacitor?.isNativePlatform?.();
  const isLocalOrigin = window.location.protocol === 'capacitor:' || 
    window.location.protocol === 'file:' || 
    window.location.hostname === 'localhost' ||
    window.location.hostname === '127.0.0.1';
  return Boolean(isCap || isLocalOrigin);
};

/**
 * Generates a YouTube embed URL that NEVER causes Error 150 in Android APKs.
 * YouTube's Iframe API rejects "capacitor://localhost" and local origins.
 * Using a safe HTTPS origin allows the embed to play on Android WebView.
 */
export const getSafeYouTubeEmbedUrl = (videoId: string, autoplay: boolean = true): string => {
  const isLocal = typeof window !== 'undefined' && (
    window.location.origin.includes('localhost') || 
    window.location.origin.includes('capacitor') ||
    window.location.protocol === 'file:'
  );
  
  // Safe origin required by YouTube to avoid Error 150 on mobile WebViews
  const safeOrigin = isLocal ? 'https://www.youtube.com' : window.location.origin;

  return `https://www.youtube.com/embed/${videoId}?enablejsapi=1&autoplay=${autoplay ? 1 : 0}&playsinline=1&controls=1&rel=0&origin=${encodeURIComponent(safeOrigin)}`;
};

/**
 * Filter offline catalog based on search keywords
 */
export const searchOfflineCatalog = (query: string): YouTubeTrack[] => {
  const cleanQ = query.toLowerCase().trim();
  if (!cleanQ) return CURATED_OFFLINE_CATALOG.slice(0, 15);

  const keywords = cleanQ.split(/\s+/).filter(Boolean);

  const scored = CURATED_OFFLINE_CATALOG.map((track) => {
    let score = 0;
    const titleLower = track.title.toLowerCase();
    const channelLower = (track.channel || '').toLowerCase();

    // Exact query matches
    if (titleLower.includes(cleanQ)) score += 50;
    if (channelLower.includes(cleanQ)) score += 30;

    // Keyword matches
    for (const kw of keywords) {
      if (titleLower.includes(kw)) score += 10;
      if (channelLower.includes(kw)) score += 5;
    }

    // Genre alias matches
    if ((cleanQ.includes('bangla') || cleanQ.includes('romantic')) && 
        (titleLower.includes('bangla') || titleLower.includes('romantic') || titleLower.includes('arijit') || titleLower.includes('habib'))) {
      score += 15;
    }
    if ((cleanQ.includes('lofi') || cleanQ.includes('chill') || cleanQ.includes('sleep')) && 
        (titleLower.includes('lofi') || titleLower.includes('chill') || titleLower.includes('relax'))) {
      score += 25;
    }
    if ((cleanQ.includes('coke') || cleanQ.includes('studio')) && titleLower.includes('coke studio')) {
      score += 25;
    }
    if ((cleanQ.includes('band') || cleanQ.includes('rock')) && 
        (titleLower.includes('rock') || titleLower.includes('warfaze') || titleLower.includes('artcell') || titleLower.includes('lrb') || titleLower.includes('miles'))) {
      score += 25;
    }
    if (cleanQ.includes('rabindra') && (titleLower.includes('rabindra') || titleLower.includes('shreya') || titleLower.includes('thakur'))) {
      score += 25;
    }

    return { track, score };
  });

  const matching = scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.track);

  if (matching.length > 0) {
    return matching;
  }

  // If no direct keyword hit, return first 12 curated tracks with query as title for first item if user searched a specific URL
  return CURATED_OFFLINE_CATALOG.slice(0, 12);
};

/**
 * Universal search executor that works in:
 * 1. Web browser (proxied via Express /api/youtube/search)
 * 2. Android APK (via Cloud Run Remote Base or Fallback to Curated Offline Library)
 * 3. Offline mobile devices
 */
export const searchYouTubeMusic = async (query: string): Promise<YouTubeTrack[]> => {
  const q = query.trim();
  if (!q) return CURATED_OFFLINE_CATALOG.slice(0, 15);

  // 1. Direct YouTube Video ID or URL pattern check
  const ytIdMatch = q.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|shorts\/))([\w-]{11})/) || 
                    (q.length === 11 && !q.includes(' ') && /^[a-zA-Z0-9_-]{11}$/.test(q) ? [null, q] : null);
  
  if (ytIdMatch && ytIdMatch[1]) {
    const directId = ytIdMatch[1];
    return [
      {
        id: directId,
        title: `YouTube Song / Video (${directId})`,
        channel: 'YouTube Video',
        duration: 'Playing',
        thumbnail: `https://i.ytimg.com/vi/${directId}/hqdefault.jpg`
      },
      ...CURATED_OFFLINE_CATALOG.slice(0, 9)
    ];
  }

  // 2. Try fetching from relative endpoint (for Web browser environment)
  if (!isAndroidNativeApp()) {
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 4000);
      const res = await fetch(`/api/youtube/search?q=${encodeURIComponent(q)}`, {
        signal: controller.signal
      });
      clearTimeout(timeoutId);
      if (res.ok) {
        const data = await res.json();
        if (data.success && Array.isArray(data.results) && data.results.length > 0) {
          return data.results;
        }
      }
    } catch (_err) {
      // Fall through to remote or offline catalog
    }
  }

  // 3. If in Android APK or if relative fetch failed, try Remote Backend Cloud Run URL
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 4500);
    const remoteUrl = `${REMOTE_API_BASE}/api/youtube/search?q=${encodeURIComponent(q)}`;
    const remoteRes = await fetch(remoteUrl, { signal: controller.signal });
    clearTimeout(timeoutId);
    if (remoteRes.ok) {
      const data = await remoteRes.json();
      if (data.success && Array.isArray(data.results) && data.results.length > 0) {
        return data.results;
      }
    }
  } catch (_e) {
    // Continue to offline matching
  }

  // 4. Guaranteed Offline / APK Search: Match with curated rich offline catalog
  const offlineResults = searchOfflineCatalog(q);
  return offlineResults;
};
